import assert from "node:assert/strict";
import { readFile, stat } from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { load } = require("js-yaml");
const pkg = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const root = path.resolve(process.argv[2] || "release-build");
const name = `RunningHub-Runner-v${pkg.version}-windows-x64-setup.exe`;
const bytes = await readFile(path.join(root, name));
assert.equal(bytes.subarray(0, 2).toString("ascii"), "MZ", "Installer must be a Windows executable");
const manifest = load(await readFile(path.join(root, "latest.yml"), "utf8"));
assert.equal(manifest.version, pkg.version);
const file = manifest.files.find(item => item.url === name);
assert.ok(file, "latest.yml must point to the installer from this build");
assert.equal(file.size, bytes.length);
assert.equal(file.sha512, createHash("sha512").update(bytes).digest("base64"));
assert.ok((await stat(path.join(root, name + ".blockmap"))).size > 0);
const feed = load(await readFile(path.join(root, "win-unpacked/resources/app-update.yml"), "utf8"));
assert.equal(feed.provider, "github");
assert.equal(feed.owner, "chiqi51386-afk");
assert.equal(feed.repo, "RunningHub-Multi-Task-Runner");
assert.equal(feed.token, undefined);
assert.equal(pkg.build.nsis.deleteAppDataOnUninstall, false);
assert.ok((await stat(path.join(root, "win-unpacked/resources/download-engine/aria2c.exe"))).size > 0, "aria2 must be bundled");
assert.ok((await stat(path.join(root, "win-unpacked/resources/download-engine/aria2-1.37.0.tar.xz"))).size > 0, "aria2 corresponding source must be bundled");
console.log("Windows installer, SHA-512 metadata, blockmap and update feed verified.");
